#!/usr/bin/env python3
"""Generate URC 2027 ArUco post models for Gazebo (rule 1.e.xii).

Each post is a pole carrying a three-sided head. Every side is a 20 x 20 cm
face showing the same 4x4_50 tag with a one-cell white border, so cells are
2.5 cm and the black marker is 15 cm.

Usage (from the package root, no third-party packages needed):
    python3 tools/make_aruco_posts.py 0 1
"""
import math
import os
import struct
import sys
import zlib

# First entries of OpenCV's DICT_4X4_1000_BYTES (4x4_50 is its first 50 ids),
# rotation 0: two bytes = 16 bits, row-major, 1 = white.
DICT_4X4_50 = {
    0: (181, 50),
    1: (15, 154),
    2: (51, 45),
    3: (153, 70),
    4: (84, 158),
}

FACE = 0.20        # face edge length, metres
HEAD_BOTTOM = 1.0  # face spans 1.0 - 1.2 m (rules allow 0.5 - 1.5 m)
POLE_RADIUS = 0.02
POLE_BURY = 0.3    # pole extends below the model origin so it works on slopes
CELL_PX = 100      # texture is 8 x 8 cells


def tag_cells(tag_id):
    """Return the 8x8 grid (True = white): white border, black border, bits."""
    b0, b1 = DICT_4X4_50[tag_id]
    bits = [(b0 >> (7 - i)) & 1 for i in range(8)]
    bits += [(b1 >> (7 - i)) & 1 for i in range(8)]
    grid = [[True] * 8 for _ in range(8)]
    for r in range(1, 7):
        for c in range(1, 7):
            inner = 2 <= r <= 5 and 2 <= c <= 5
            grid[r][c] = bool(bits[(r - 2) * 4 + (c - 2)]) if inner else False
    return grid


def write_png(path, grid):
    size = 8 * CELL_PX
    rows = bytearray()
    for r in range(size):
        rows.append(0)  # filter type: none
        for c in range(size):
            rows.extend(b'\xff\xff\xff' if grid[r // CELL_PX][c // CELL_PX]
                        else b'\x00\x00\x00')

    def chunk(kind, data):
        body = kind + data
        return (struct.pack('>I', len(data)) + body
                + struct.pack('>I', zlib.crc32(body) & 0xffffffff))

    ihdr = struct.pack('>IIBBBBB', size, size, 8, 2, 0, 0, 0)
    with open(path, 'wb') as f:
        f.write(b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', ihdr)
                + chunk(b'IDAT', zlib.compress(bytes(rows), 9))
                + chunk(b'IEND', b''))


def write_head_obj(path):
    """Triangular prism. Each side maps the full texture, unmirrored when
    viewed from outside (u left-to-right, v bottom-to-top)."""
    radius = FACE / math.sqrt(3.0)
    # Corners counter-clockwise seen from above.
    corners = [(radius * math.cos(math.radians(a)),
                radius * math.sin(math.radians(a))) for a in (210, 330, 90)]
    z0, z1 = HEAD_BOTTOM, HEAD_BOTTOM + FACE
    out = ['# URC 2027 ArUco post head (generated by tools/make_aruco_posts.py)',
           'o aruco_post_head']
    for x, y in corners:
        out.append(f'v {x:.6f} {y:.6f} {z0:.6f}')
    for x, y in corners:
        out.append(f'v {x:.6f} {y:.6f} {z1:.6f}')
    out += ['vt 0 0', 'vt 1 0', 'vt 1 1', 'vt 0 1',
            'vt 0.03 0.03']  # 5: a white border pixel, for the caps
    for i in range(3):
        (x0, y0), (x1, y1) = corners[i], corners[(i + 1) % 3]
        nx, ny = (y1 - y0) / FACE, -(x1 - x0) / FACE
        out.append(f'vn {nx:.6f} {ny:.6f} 0')
    out += ['vn 0 0 1', 'vn 0 0 -1']
    for i in range(3):
        a, b = i + 1, (i + 1) % 3 + 1          # bottom-left, bottom-right
        n = i + 1
        out.append(f'f {a}/1/{n} {b}/2/{n} {b + 3}/3/{n} {a + 3}/4/{n}')
    out.append('f 4/5/4 5/5/4 6/5/4')          # top cap
    out.append('f 3/5/5 2/5/5 1/5/5')          # bottom cap
    with open(path, 'w', newline='\n') as f:
        f.write('\n'.join(out) + '\n')


MODEL_SDF = """<?xml version="1.0" ?>
<sdf version="1.8">
  <!-- URC 2027 ArUco post, 4x4_50 id {id}. Generated by tools/make_aruco_posts.py -->
  <model name="aruco_post_{id}">
    <static>true</static>
    <link name="link">
      <visual name="pole">
        <pose>0 0 {pole_z:.3f} 0 0 0</pose>
        <geometry>
          <cylinder><radius>{pole_r}</radius><length>{pole_len:.3f}</length></cylinder>
        </geometry>
        <material>
          <ambient>0.6 0.6 0.6 1</ambient>
          <diffuse>0.6 0.6 0.6 1</diffuse>
        </material>
      </visual>
      <visual name="head">
        <geometry>
          <mesh><uri>model://aruco_post_{id}/meshes/aruco_post_head.obj</uri></mesh>
        </geometry>
        <material>
          <diffuse>1 1 1 1</diffuse>
          <specular>0 0 0 1</specular>
          <pbr>
            <metal>
              <albedo_map>materials/textures/aruco_4x4_50_{id}.png</albedo_map>
              <metalness>0.0</metalness>
              <roughness>1.0</roughness>
            </metal>
          </pbr>
        </material>
      </visual>
      <collision name="pole">
        <pose>0 0 {pole_z:.3f} 0 0 0</pose>
        <geometry>
          <cylinder><radius>{pole_r}</radius><length>{pole_len:.3f}</length></cylinder>
        </geometry>
      </collision>
      <collision name="head">
        <pose>0 0 {head_z:.3f} 0 0 0</pose>
        <geometry>
          <cylinder><radius>{head_r:.3f}</radius><length>{face}</length></cylinder>
        </geometry>
      </collision>
    </link>
  </model>
</sdf>
"""

MODEL_CONFIG = """<?xml version="1.0"?>
<model>
  <name>aruco_post_{id}</name>
  <version>1.0</version>
  <sdf version="1.8">model.sdf</sdf>
  <author>
    <name>TROS</name>
  </author>
  <description>URC 2027 three-sided ArUco post, 4x4_50 id {id}</description>
</model>
"""


def make_post(models_dir, tag_id):
    root = os.path.join(models_dir, f'aruco_post_{tag_id}')
    os.makedirs(os.path.join(root, 'meshes'), exist_ok=True)
    os.makedirs(os.path.join(root, 'materials', 'textures'), exist_ok=True)
    write_png(os.path.join(root, 'materials', 'textures',
                           f'aruco_4x4_50_{tag_id}.png'), tag_cells(tag_id))
    write_head_obj(os.path.join(root, 'meshes', 'aruco_post_head.obj'))
    pole_len = HEAD_BOTTOM + POLE_BURY
    values = dict(id=tag_id, pole_r=POLE_RADIUS, pole_len=pole_len,
                  pole_z=pole_len / 2 - POLE_BURY, face=FACE,
                  head_z=HEAD_BOTTOM + FACE / 2, head_r=FACE / math.sqrt(3.0))
    with open(os.path.join(root, 'model.sdf'), 'w', newline='\n') as f:
        f.write(MODEL_SDF.format(**values))
    with open(os.path.join(root, 'model.config'), 'w', newline='\n') as f:
        f.write(MODEL_CONFIG.format(**values))
    print('wrote', root)


def main():
    ids = [int(a) for a in sys.argv[1:]] or [0, 1]
    unknown = [i for i in ids if i not in DICT_4X4_50]
    if unknown:
        sys.exit(f'ids {unknown} are not in the embedded table; add their '
                 'bytes from OpenCV predefined_dictionaries.hpp')
    models_dir = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                              '..', 'models')
    for tag_id in ids:
        make_post(os.path.normpath(models_dir), tag_id)


if __name__ == '__main__':
    main()
