#!/usr/bin/env python3
"""Build the Gazebo terrain model (models/urc_terrain) from a GeoTIFF DEM.

Cuts a square tile out of the DEM, writes it as a 16-bit heightmap, adds an
aerial photo for the ground colour, and writes the model files. The photo is
downloaded from the USGS NAIP imagery service (public domain, 0.6 m per pixel)
unless --imagery names an ArcGIS tile package (.tpkx) to take it from instead.

The tile centre becomes the Gazebo world x/y origin. World z is height above
the lowest point of the tile, so the ground at the origin is NOT at z=0; the
value is written to models/urc_terrain/terrain.yaml, which the launch file
reads to spawn the rover at the right height.

    python3 tools/make_terrain.py ~/Downloads/output.tin.tif
    python3 tools/make_terrain.py DEM.tif --center 519540.98 4252063.57 --size 1024
    python3 tools/make_terrain.py DEM.tif --imagery World_Imagery.tpkx --texture-px 4096
    python3 tools/make_terrain.py --height-at 110 -100     # world z of the ground

Needs GDAL's Python bindings (python3-gdal) and Pillow. After running, copy the
printed latitude/longitude/elevation into <spherical_coordinates> in
world/rover_world.sdf, then rebuild the package.
"""
import argparse
import io
import math
import os
import re
import urllib.parse
import urllib.request
import zipfile
from json import loads as json_load

import numpy as np
from osgeo import gdal, osr
from PIL import Image, ImageFilter

gdal.UseExceptions()

NAIP_URL = ('https://imagery.nationalmap.gov/arcgis/rest/services/'
            'USGSNAIPImagery/ImageServer/exportImage')
MODEL_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                         '..', 'models', 'urc_terrain')

MODEL_SDF = """<?xml version="1.0" ?>
<sdf version="1.8">
  <!-- Generated by tools/make_terrain.py - do not edit by hand.
       Tile centre (world origin): UTM {east:.2f} E, {north:.2f} N (EPSG:{epsg})
       {lat:.7f}, {lon:.7f}; ground there is at world z = {origin_z:.3f} m
       World z = elevation - {hmin:.2f} m -->
  <model name="urc_terrain">
    <static>true</static>
    <!-- The lowest point of the tile is at z=0. Do not try to shift it with
         <pose> or the heightmap <pos>: the physics engine ignores both for
         heightmaps, so the visible ground and the solid ground come apart. -->
    <link name="link">
      <collision name="collision">
        <geometry>
          <heightmap>
            <uri>model://urc_terrain/materials/textures/heightmap.png</uri>
            <size>{size:.1f} {size:.1f} {dz:.3f}</size>
            <pos>0 0 0</pos>
          </heightmap>
        </geometry>
      </collision>
      <visual name="visual">
        <geometry>
          <heightmap>
            <use_terrain_paging>false</use_terrain_paging>
            <texture>
              <diffuse>model://urc_terrain/materials/textures/aerial.png</diffuse>
              <normal>model://urc_terrain/materials/textures/flat_normal.png</normal>
              <size>{size:.1f}</size>
            </texture>
            <uri>model://urc_terrain/materials/textures/heightmap.png</uri>
            <size>{size:.1f} {size:.1f} {dz:.3f}</size>
            <pos>0 0 0</pos>
          </heightmap>
        </geometry>
      </visual>
    </link>
  </model>
</sdf>
"""

MODEL_CONFIG = """<?xml version="1.0"?>
<model>
  <name>urc_terrain</name>
  <version>1.0</version>
  <sdf version="1.8">model.sdf</sdf>
  <description>URC site terrain cut from a lidar DEM, coloured with {imagery}.</description>
</model>
"""


def open_tile_package(path):
    """Mosaic the sharpest level of an ArcGIS tile package into a GDAL dataset.

    A .tpkx is a zip holding root.json (the tiling scheme) and, per zoom level,
    "bundle" files of up to 128 x 128 tiles each. A bundle is a 64-byte header,
    then one 8-byte index entry per tile (low 40 bits = file offset, high 24
    bits = byte length, 0 when the tile is absent), then the tile images.
    Exports include empty bundles for levels beyond what the imagery has, so
    this uses the deepest level that actually holds tiles.
    """
    package = zipfile.ZipFile(path)
    info = json_load(package.read('root.json'))['tileInfo']
    px = info['rows']
    if info['spatialReference'].get('latestWkid') != 3857 or info['cols'] != px:
        raise SystemExit('Only Web Mercator tile packages with square tiles are supported.')
    resolution = {lod['level']: lod['resolution'] for lod in info['lods']}

    levels = {}
    for name in package.namelist():
        match = re.fullmatch(r'tile/L(\d+)/R([0-9a-f]+)C([0-9a-f]+)\.bundle', name)
        if match:
            levels.setdefault(int(match.group(1)), []).append(
                (name, int(match.group(2), 16), int(match.group(3), 16)))
    for level in sorted(levels, reverse=True):
        tiles = {}
        for name, row0, col0 in levels[level]:
            data = package.read(name)
            index = np.frombuffer(data, '<u8', 128 * 128, 64)
            for i in np.flatnonzero(index >> 40):
                offset, size = int(index[i]) & (2 ** 40 - 1), int(index[i]) >> 40
                tiles[row0 + i // 128, col0 + i % 128] = data[offset:offset + size]
        if tiles:
            break
    else:
        raise SystemExit(f'No tiles found in {path}')

    rows = [r for r, _ in tiles]
    cols = [c for _, c in tiles]
    row0, col0 = min(rows), min(cols)
    mosaic = np.zeros(((max(rows) - row0 + 1) * px, (max(cols) - col0 + 1) * px, 4), np.uint8)
    for (row, col), data in tiles.items():
        tile = np.asarray(Image.open(io.BytesIO(data)).convert('RGBA'))
        mosaic[(row - row0) * px:(row - row0 + 1) * px,
               (col - col0) * px:(col - col0 + 1) * px] = tile

    res = resolution[level]
    out = gdal.GetDriverByName('MEM').Create('', mosaic.shape[1], mosaic.shape[0], 4, gdal.GDT_Byte)
    out.SetGeoTransform([info['origin']['x'] + col0 * px * res, res, 0,
                         info['origin']['y'] - row0 * px * res, 0, -res])
    mercator = osr.SpatialReference()
    mercator.ImportFromEPSG(3857)
    out.SetProjection(mercator.ExportToWkt())
    for band in range(4):
        out.GetRasterBand(band + 1).WriteArray(mosaic[..., band])
    out.GetRasterBand(4).SetColorInterpretation(gdal.GCI_AlphaBand)
    return out, level, res


def tiles_latitude(source, srs, east, north):
    """Latitude of a point given in the DEM coordinate system."""
    wgs84 = osr.SpatialReference()
    wgs84.ImportFromEPSG(4326)
    wgs84.SetAxisMappingStrategy(osr.OAMS_TRADITIONAL_GIS_ORDER)
    local = srs.Clone()
    local.SetAxisMappingStrategy(osr.OAMS_TRADITIONAL_GIS_ORDER)
    return osr.CoordinateTransformation(local, wgs84).TransformPoint(east, north)[1]


def add_lidar_detail(photo, source, east, north, half, metres_per_px, strength):
    """Multiply the photo by relief shading finer than the photo can resolve.

    The NAIP photo is 0.6 m per pixel; a lidar DEM can be much finer. Shading the
    DEM and keeping only features smaller than about 3 m (the photo already
    shows larger ones) adds real rocks, gullies and bushes in the right places.
    Colours still come from the photo.
    """
    px = photo.width
    fine = gdal.Warp('', source, format='MEM', resampleAlg='bilinear',
                     width=px, height=px, dstNodata=-9999,
                     outputBounds=[east - half, north - half, east + half, north + half])
    gdal.FillNodata(fine.GetRasterBand(1), None, maxSearchDist=px, smoothingIterations=0)
    shade = gdal.DEMProcessing('', fine, 'hillshade', format='MEM',
                               multiDirectional=True, zFactor=2.0, computeEdges=True)
    shade = Image.fromarray(shade.GetRasterBand(1).ReadAsArray().astype(np.uint8))
    smooth = shade.filter(ImageFilter.GaussianBlur(radius=3.0 / metres_per_px))
    ratio = (np.asarray(shade, np.float32) + 8) / (np.asarray(smooth, np.float32) + 8)
    ratio = np.clip(ratio, 0.55, 1.45) ** strength
    out = np.asarray(photo, np.float32) * ratio[..., None]
    return Image.fromarray(np.clip(out, 0, 255).astype(np.uint8))


def main():
    parser = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    parser.add_argument('dem', nargs='?',
                        help='GeoTIFF DEM in a projected (metre) coordinate system')
    parser.add_argument('--height-at', nargs=2, type=float, metavar=('X', 'Y'),
                        help='print the ground z at world x, y from the existing model and exit')
    parser.add_argument('--center', nargs=2, type=float, metavar=('EAST', 'NORTH'),
                        default=[519540.98, 4252063.57],
                        help='tile centre in the DEM coordinate system')
    parser.add_argument('--size', type=float, default=1024.0, help='tile side in metres')
    parser.add_argument('--samples', type=int, default=1025,
                        help='heightmap points per side; must be 2^n + 1')
    parser.add_argument('--texture-px', type=int, default=2048,
                        help='ground texture size in pixels')
    parser.add_argument('--lidar-detail', type=float, default=0.0, metavar='STRENGTH',
                        help='sharpen the photo with fine relief shading from the DEM '
                             '(0 = off, 1 = normal). Use with --texture-px 4096 when the '
                             'DEM is finer than the 0.6 m photo')
    parser.add_argument('--imagery', metavar='TPKX',
                        help='take the ground photo from this ArcGIS tile package '
                             'instead of downloading NAIP')
    parser.add_argument('--no-imagery', action='store_true',
                        help='skip the download and keep the existing aerial.png')
    args = parser.parse_args()

    if args.height_at:
        ground = np.load(os.path.join(MODEL_DIR, 'height_m.npy'))
        mid = ground.shape[0] // 2
        step = float(open(os.path.join(MODEL_DIR, 'terrain.yaml')).read()
                     .split('point_spacing_m:')[1].split()[0])
        x, y = args.height_at
        print(f'{ground[mid - round(y / step), mid + round(x / step)]:.2f}')
        return
    if not args.dem:
        parser.error('a DEM file is required')

    if (args.samples - 1) & (args.samples - 2) or args.samples < 3:
        parser.error('--samples must be 2^n + 1 (513, 1025, 2049, ...)')

    east, north = args.center
    half = args.size / 2.0
    step = args.size / (args.samples - 1)
    source = gdal.Open(os.path.expanduser(args.dem))
    srs = osr.SpatialReference(wkt=source.GetProjection())
    epsg = srs.GetAuthorityCode(None)

    # One pixel per heightmap point, so the outer pixel centres sit exactly on
    # the tile edge. Averaging avoids aliasing when the DEM is finer.
    tile = gdal.Warp(
        '', source, format='MEM', resampleAlg='average',
        xRes=step, yRes=step, dstNodata=-9999,
        outputBounds=[east - half - step / 2, north - half - step / 2,
                      east + half + step / 2, north + half + step / 2])
    band = tile.GetRasterBand(1)
    missing = float(np.mean(band.ReadAsArray() == -9999))
    gdal.FillNodata(band, None, maxSearchDist=int(args.samples), smoothingIterations=0)
    height = band.ReadAsArray().astype(np.float64)   # row 0 is the north edge
    if (height == -9999).any():
        raise SystemExit('The tile still has holes after filling; move --center.')

    hmin, hmax = float(height.min()), float(height.max())
    mid = args.samples // 2
    h0 = float(height[mid, mid])
    scaled = np.round((height - hmin) / (hmax - hmin) * 65535).astype(np.uint16)

    textures = os.path.join(MODEL_DIR, 'materials', 'textures')
    os.makedirs(textures, exist_ok=True)
    Image.fromarray(scaled).save(os.path.join(textures, 'heightmap.png'))
    Image.new('RGB', (16, 16), (128, 128, 255)).save(
        os.path.join(textures, 'flat_normal.png'))

    imagery = 'an aerial photo' if args.no_imagery else 'USGS NAIP aerial imagery'
    if args.imagery and not args.no_imagery:
        imagery = 'imagery from ' + os.path.basename(args.imagery)
        tiles, level, res = open_tile_package(os.path.expanduser(args.imagery))
        photo = gdal.Warp(
            '', tiles, format='MEM', dstSRS=f'EPSG:{epsg}', resampleAlg='cubic',
            width=args.texture_px, height=args.texture_px, dstAlpha=True,
            outputBounds=[east - half, north - half, east + half, north + half])
        rgba = photo.ReadAsArray().transpose(1, 2, 0)
        uncovered = float(np.mean(rgba[..., 3] == 0))
        if uncovered > 0.001:
            raise SystemExit(f'The tile package does not cover {uncovered:.1%} of the '
                             'terrain tile; export a larger area.')
        Image.fromarray(rgba[..., :3]).save(os.path.join(textures, 'aerial_source.png'))
        # Web Mercator stretches distances by 1/cos(latitude).
        lat_scale = math.cos(math.radians(tiles_latitude(source, srs, east, north)))
        print(f'  imagery: level {level}, {res * lat_scale:.2f} m per pixel on the ground; '
              f'texture is {args.size / args.texture_px:.2f} m per pixel')
    elif not args.no_imagery:
        # The photo is 0.6 m per pixel at best, so there is nothing to gain from
        # downloading more pixels than that (and the service refuses over 4000).
        photo_px = int(min(args.texture_px, 4000, max(256, args.size / 0.5)))
        query = urllib.parse.urlencode({
            'bbox': f'{east - half},{north - half},{east + half},{north + half}',
            'bboxSR': epsg, 'imageSR': epsg,
            'size': f'{photo_px},{photo_px}',
            'interpolation': 'RSP_CubicConvolution',
            'format': 'png', 'bandIds': '0,1,2', 'f': 'image'})
        request = urllib.request.Request(f'{NAIP_URL}?{query}',
                                         headers={'User-Agent': 'make_terrain.py'})
        with urllib.request.urlopen(request, timeout=120) as response:
            data = response.read()
        if not data.startswith(b'\x89PNG'):
            raise SystemExit('Imagery service did not return an image:\n'
                             + data[:300].decode(errors='replace'))
        with open(os.path.join(textures, 'aerial_source.png'), 'wb') as f:
            f.write(data)

    # aerial_source.png is the photo as downloaded; aerial.png is what Gazebo uses.
    photo = Image.open(os.path.join(textures, 'aerial_source.png')).convert('RGB')
    px = args.texture_px
    photo = photo.resize((px, px), Image.LANCZOS)
    if args.lidar_detail > 0:
        photo = add_lidar_detail(photo, source, east, north, half, args.size / px,
                                 args.lidar_detail)
    photo.save(os.path.join(textures, 'aerial.png'))

    wgs84 = osr.SpatialReference()
    wgs84.ImportFromEPSG(4326)
    wgs84.SetAxisMappingStrategy(osr.OAMS_TRADITIONAL_GIS_ORDER)
    srs.SetAxisMappingStrategy(osr.OAMS_TRADITIONAL_GIS_ORDER)
    lon, lat, _ = osr.CoordinateTransformation(srs, wgs84).TransformPoint(east, north)

    values = dict(east=east, north=north, epsg=epsg, lat=lat, lon=lon, hmin=hmin,
                  size=args.size, dz=hmax - hmin, origin_z=h0 - hmin)
    with open(os.path.join(MODEL_DIR, 'model.sdf'), 'w') as f:
        f.write(MODEL_SDF.format(**values))
    with open(os.path.join(MODEL_DIR, 'model.config'), 'w') as f:
        f.write(MODEL_CONFIG.format(imagery=imagery))
    # Ground height in world z (row 0 is the north edge), for placing props.
    np.save(os.path.join(MODEL_DIR, 'height_m.npy'), (height - hmin).astype(np.float32))
    with open(os.path.join(MODEL_DIR, 'terrain.yaml'), 'w') as f:
        f.write('# Generated by tools/make_terrain.py\n'
                f'origin_ground_z: {h0 - hmin:.3f}   # world z of the ground at x=0, y=0\n'
                f'origin_latitude_deg: {lat:.7f}\n'
                f'origin_longitude_deg: {lon:.7f}\n'
                f'z0_elevation_m: {hmin:.2f}        # real elevation of world z=0\n'
                f'size_m: {args.size:.1f}\n'
                f'point_spacing_m: {step:.4f}\n')


    print(f'Wrote {os.path.normpath(MODEL_DIR)}')
    print(f'  tile {args.size:.0f} m square, {args.samples} points per side ({step:.2f} m apart)')
    print(f'  elevation {hmin:.2f} to {hmax:.2f} m; {missing:.1%} of the tile was empty and filled')
    print('  <spherical_coordinates> for the world file:')
    print(f'    latitude_deg {lat:.7f}  longitude_deg {lon:.7f}  elevation {hmin:.2f}')
    print(f'  ground at the origin is at world z = {h0 - hmin:.3f}')


if __name__ == '__main__':
    main()
